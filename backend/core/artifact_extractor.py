@dataclass
class ReqArtifacts:
    """Artifacts produced and consumed by a single requirement."""
    req_index: int
    req_id: str
    produced: Set[str] = field(default_factory=set)
    consumed: Set[str] = field(default_factory=set)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "req_index": self.req_index,
            "req_id": self.req_id,
            "produced": sorted(self.produced),
            "consumed": sorted(self.consumed),
        }


def extract_artifacts(
    texts: Sequence[str],
    req_ids: Sequence[str],
    use_spacy: Optional[bool] = None,
    batch_size: int = 256,
) -> List[ReqArtifacts]:
    """Extract produced and consumed artifact names from requirement texts.

    Args:
        texts:    Requirement text strings, length N.
        req_ids:  Requirement identifiers.  Shorter/longer lists are tolerated;
                  missing identifiers fall back to a positional ``REQ-<i>``.
        use_spacy: Force the back-end.  ``None`` (default) auto-selects spaCy
                  when available and silently falls back to regex otherwise.
        batch_size: spaCy ``nlp.pipe`` batch size.

    Returns:
        List of :class:`ReqArtifacts`, one per requirement, in input order.

    Example::

        texts = [
            "The system shall generate an altitude report every second.",
            "The altitude report shall be consumed by the display formatter.",
        ]
        arts = extract_artifacts(texts, ["REQ-001", "REQ-002"])
        # arts[0].produced == {"altitude report"}
        # arts[1].consumed == {"altitude report"}
    """
    texts = list(texts)
    n = len(texts)

    def _rid(i: int) -> str:
        if i < len(req_ids) and req_ids[i]:
            return str(req_ids[i])
        return f"REQ-{i + 1:03d}"

    nlp = _load_nlp() if use_spacy is not False else None
    if use_spacy is True and nlp is None:
        raise RuntimeError(
            "spaCy artifact extraction was requested but the pipeline "
            f"({_SPACY_MODEL}) is unavailable."
        )

    results: List[ReqArtifacts] = []

    if nlp is not None:
        safe_texts = [t if isinstance(t, str) else "" for t in texts]
        try:
            docs = nlp.pipe(safe_texts, batch_size=max(1, int(batch_size)))
            for idx, doc in enumerate(docs):
                produced, consumed = _extract_artifacts_spacy(doc)
                results.append(
                    ReqArtifacts(idx, _rid(idx), produced=produced, consumed=consumed)
                )
        except Exception:
            # A parser failure must never take the pipeline down; degrade to the
            # regex path for the whole batch so the result stays internally
            # consistent rather than half-parsed.
            logger.exception(
                "spaCy extraction failed — falling back to regex extraction."
            )
            results = []
        else:
            return results

    for idx in range(n):
        text = texts[idx] if isinstance(texts[idx], str) else ""
        ra = ReqArtifacts(req_index=idx, req_id=_rid(idx))
        for sent in _sentences(text):
            ra.produced.update(_extract_np_after_verb(sent, _OUT_VERB_RE))
            ra.consumed.update(_extract_np_after_verb(sent, _IN_VERB_RE))
        results.append(ra)
    return results


def build_artifact_index(
    artifacts: Sequence[ReqArtifacts],
) -> Tuple[Dict[str, List[int]], Dict[str, List[int]]]:
    """Build lookup tables: artifact_name -> list of producer/consumer indices.

    Args:
        artifacts: Output of :func:`extract_artifacts`.

    Returns:
        ``(producers, consumers)``, each ``{artifact_name: [req_index, ...]}``
        with indices in ascending order.
    """
    producers: Dict[str, List[int]] = {}
    consumers: Dict[str, List[int]] = {}

    for ra in artifacts:
        for art in sorted(ra.produced):
            producers.setdefault(art, []).append(ra.req_index)
        for art in sorted(ra.consumed):
            consumers.setdefault(art, []).append(ra.req_index)

    return producers, consumers


# ---------------------------------------------------------------------------
# Embedding near-match (opt-in)
# ---------------------------------------------------------------------------

# Guard rail: pairwise similarity over unique artifact names is O(U^2).  Beyond
# this many unique names the step is skipped rather than silently costing
# minutes and gigabytes on a large corpus.
MAX_NEAR_MATCH_NAMES = 4000

# Tuned with tools/eval_dependency_tree.py rather than by feel.  Sweeping the
# threshold over both harness datasets (detection precision / recall / F1):
#
#   threshold | aerospace P | adversarial F1 | merges
#   ----------|-------------|----------------|-------
#   off       |    0.387    |     0.821      |   0
#   0.85      |    0.387    |     0.850      |   1
#   0.80      |    0.387    |     0.889      |   5
#   0.75      |    0.387    |     0.913      |   6   <- chosen
#   0.65      |    0.387    |     0.913      |   6
#   0.60      |    0.375    |     0.913      |   6   <- precision starts to slip
#
# 0.75 is the loosest threshold that still leaves the original aerospace set's
# precision untouched while capturing every synonym pair the adversarial set
# was built to expose.
DEFAULT_NEAR_MATCH_THRESHOLD = 0.75

_NEAR_MATCH_BLOCK = 512


def _canonical_of(a: str, b: str) -> str:
    """Deterministic canonical choice between two synonymous names."""
    if len(a) != len(b):
        return a if len(a) < len(b) else b
    return min(a, b)


def resolve_near_matches(
    producers: Dict[str, List[int]],
    consumers: Dict[str, List[int]],
    similarity_threshold: float = DEFAULT_NEAR_MATCH_THRESHOLD,
    embed_fn: Optional[Callable[[List[str]], Any]] = None,
) -> Tuple[Dict[str, List[int]], Dict[str, List[int]], Dict[str, Any]]:
    """Merge synonymous producer/consumer artifact names via embedding similarity.

    Exact string equality after normalisation misses "temperature reading" vs.
    "temp value".  This embeds each *unique* artifact name — there are far fewer
    of these than requirements, and they hit the same SBERT/Redis cache as the
    main pass, so the added cost is small — and merges producer names with
    consumer names above *similarity_threshold* under a single canonical name.

    Args:
        producers: ``{artifact_name: [req_index, ...]}`` from
            :func:`build_artifact_index`.
        consumers: likewise for consumed artifacts.
        similarity_threshold: minimum cosine similarity to merge.  Defaults to
            :data:`DEFAULT_NEAR_MATCH_THRESHOLD`, chosen from the harness sweep
            recorded beside that constant.
        embed_fn: override for the embedding function (tests / alternate models).
            Defaults to ``core.embeddings.generate_embeddings``.

    Returns:
        ``(producers, consumers, report)``.  The inputs are not mutated.
        ``report`` records each merge as
        ``{"from": name, "to": canonical, "similarity": float}`` plus a
        ``skipped`` reason when the step declined to run.
    """
    report: Dict[str, Any] = {"merges": [], "skipped": None}

    unique_names = sorted(set(producers) | set(consumers))
    if not producers or not consumers or len(unique_names) < 2:
        report["skipped"] = "not enough artifact names to compare"
        return dict(producers), dict(consumers), report

    if len(unique_names) > MAX_NEAR_MATCH_NAMES:
        msg = (
            f"{len(unique_names)} unique artifact names exceeds the "
            f"{MAX_NEAR_MATCH_NAMES} near-match limit"
        )
        logger.warning("resolve_near_matches skipped: %s.", msg)
        report["skipped"] = msg
        return dict(producers), dict(consumers), report

    try:
        import numpy as np  # noqa: PLC0415

        if embed_fn is None:
            # Imported lazily so this module stays importable (and the regex
            # path stays usable) in environments without torch/SBERT.
            from .embeddings import generate_embeddings  # noqa: PLC0415

            embed_fn = generate_embeddings

        vectors = np.asarray(embed_fn(list(unique_names)), dtype=np.float32)
    except Exception as exc:
        logger.warning("resolve_near_matches skipped: embedding failed (%s).", exc)
        report["skipped"] = f"embedding failed: {exc}"
        return dict(producers), dict(consumers), report

    if vectors.ndim != 2 or vectors.shape[0] != len(unique_names):
        report["skipped"] = "embedding returned an unexpected shape"
        logger.warning("resolve_near_matches skipped: %s.", report["skipped"])
        return dict(producers), dict(consumers), report

    norms = np.linalg.norm(vectors, axis=1, keepdims=True)
    norms[norms == 0] = 1.0
    vectors = vectors / norms

    index_of = {name: i for i, name in enumerate(unique_names)}
    producer_names = sorted(producers)
    consumer_names = sorted(consumers)
    consumer_matrix = vectors[[index_of[c] for c in consumer_names]]

    # name -> (canonical, similarity); only cross-side (producer<->consumer)
    # merges are considered, which is what Pass 0 actually joins on.
    rename: Dict[str, Tuple[str, float]] = {}

    for start in range(0, len(producer_names), _NEAR_MATCH_BLOCK):
        block = producer_names[start: start + _NEAR_MATCH_BLOCK]
        block_matrix = vectors[[index_of[p] for p in block]]
        sims = block_matrix @ consumer_matrix.T
        for row, p_name in enumerate(block):
            for col, c_name in enumerate(consumer_names):
                if p_name == c_name:
                    continue  # already an exact match
                score = float(sims[row, col])
                if score < similarity_threshold:
                    continue
                canonical = _canonical_of(p_name, c_name)
                other = c_name if canonical == p_name else p_name
                # Keep the strongest merge proposed for any given name so the
                # result does not depend on iteration order.
                previous = rename.get(other)
                if previous is None or score > previous[1]:
                    rename[other] = (canonical, score)

    # A name chosen as someone's canonical must not itself be renamed away, or
    # the two sides would land on different keys and the join would still fail.
    for name in list(rename):
        canonical, _ = rename[name]
        if canonical in rename:
            del rename[name]

    if not rename:
        return dict(producers), dict(consumers), report

    def _apply(table: Dict[str, List[int]]) -> Dict[str, List[int]]:
        merged: Dict[str, List[int]] = {}
        for name, indices in table.items():
            target = rename.get(name, (name, 0.0))[0]
            bucket = merged.setdefault(target, [])
            for i in indices:
                if i not in bucket:
                    bucket.append(i)
        return {k: sorted(v) for k, v in merged.items()}

    report["merges"] = [
        {"from": name, "to": canonical, "similarity": round(score, 4)}
        for name, (canonical, score) in sorted(rename.items())
    ]
    logger.info(
        "resolve_near_matches merged %d artifact name(s) at threshold %.2f.",
        len(rename), similarity_threshold,
    )
    return _apply(producers), _apply(consumers), report
