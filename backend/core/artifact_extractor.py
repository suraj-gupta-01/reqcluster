"""Artifact extraction for producer-consumer dependency inference (DP5).

For each requirement, identifies the named data items / signals / states it
**produces** (generates, outputs, stores …) and **consumes** (reads, receives,
depends on …). This drives Pass 0 in ``dependency_tree.build_dependency_tree``.

Extraction strategy
-------------------
Two interchangeable back-ends produce the same ``ReqArtifacts`` shape:

``spaCy`` (preferred)
    Dependency-parse-driven SVO extraction.  Handles passive voice
    ("the altitude report shall be generated by …"), coordination
    ("altitude and heading data"), and verb+preposition frames
    ("depend on X") — all of which the regex back-end silently misses.
    Requires ``spacy`` plus the ``en_core_web_sm`` model (~13 MB, one extra
    one-time download on top of the SBERT model).

``regex`` (fallback)
    The original noun-phrase-after-verb scanner.  Used verbatim whenever spaCy
    or its model is unavailable, mirroring the ``sentence_transformers``
    try/except degradation already used in ``embeddings.py``.  The app never
    hard-fails for want of spaCy.

Design principles
-----------------
* Deterministic — no LLM or external network calls.
* Artifact names are normalized (lower-case, articles stripped, whitespace
  collapsed) so that "an Altitude Report" and "altitude report" match.
* An optional near-match step (:func:`resolve_near_matches`) merges synonymous
  artifact names ("temperature reading" / "temp value") using embedding cosine
  similarity.  It is **opt-in** so Pass 0 precision cannot regress silently.
"""

from __future__ import annotations

import logging
import os
import re
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional, Sequence, Set, Tuple

from .verb_lexicon import INPUT_VERBS, OUTPUT_VERBS

logger = logging.getLogger(__name__)

# Verb banks live in verb_lexicon.py — single source of truth shared with
# dependency_tree.py.  Re-exported here for backwards compatibility with
# callers/tests that imported them from this module.
_OUTPUT_VERBS: Tuple[str, ...] = OUTPUT_VERBS
_INPUT_VERBS: Tuple[str, ...] = INPUT_VERBS

_OUTPUT_VERB_SET = frozenset(OUTPUT_VERBS)
_INPUT_VERB_SET = frozenset(INPUT_VERBS)

# ---------------------------------------------------------------------------
# Shared normalisation / filtering
# ---------------------------------------------------------------------------

# Articles and determiners to strip from the front of an extracted NP.
_ARTICLE_RE = re.compile(
    r"^(?:a|an|the|this|that|each|every|its|their|all)\s+",
    re.IGNORECASE,
)

# Very generic words that are not meaningful artifact names on their own.
_GENERIC = {
    "data", "information", "value", "values", "result", "results",
    "output", "outputs", "input", "inputs", "status", "state", "signal",
    "message", "packet", "event", "response", "request", "report",
    "update", "feed", "stream", "buffer", "record", "records",
    "system", "unit", "module", "function", "interface", "parameter",
    "configuration", "setting", "mode", "level", "error", "alert",
    "notification", "log", "list", "table", "set", "map", "matrix",
    "index", "identifier", "code", "count", "rate", "flag", "bit",
    "byte", "field", "item", "object", "entity", "type", "class",
    "process", "thread", "task", "service", "component", "element",
}

# Measurement units and bare quantities: never artifacts, only qualifiers.
# ("at 20 Hz", "within 50 milliseconds", "of 3 percent")
_UNIT_WORDS = {
    "hz", "khz", "mhz", "ghz", "ms", "us", "ns", "s", "sec", "second",
    "seconds", "millisecond", "milliseconds", "microsecond", "microseconds",
    "minute", "minutes", "hour", "hours", "day", "days",
    "percent", "pct", "degree", "degrees", "celsius", "kelvin", "fahrenheit",
    "volt", "volts", "amp", "amps", "ampere", "amperes", "watt", "watts",
    "meter", "meters", "metre", "metres", "km", "cm", "mm", "micron",
    "microns", "kg", "gram", "grams", "newton", "newtons", "bar", "psi",
    "db", "dbm", "bps", "kbps", "mbps", "gbps", "byte", "bytes",
    "kilobyte", "megabyte", "gigabyte", "megabytes", "gigabytes",
    "g", "rms", "sigma", "times", "cycle", "cycles",
}

_DIGIT_RE = re.compile(r"\d")


def _normalize(text: str) -> str:
    """Lower-case, strip leading article, collapse whitespace."""
    t = text.strip().lower()
    t = _ARTICLE_RE.sub("", t)
    return re.sub(r"\s+", " ", t).strip()


def _acceptable_artifact(norm: str) -> bool:
    """Reject too-short, purely generic, and unit/quantity-only candidates."""
    if len(norm) < 3:
        return False
    if norm in _GENERIC:
        return False
    words = norm.split()
    if not words:
        return False
    # "20 hz", "3 percent", "50 milliseconds" — a quantity, not an artifact.
    if all(w in _UNIT_WORDS or _DIGIT_RE.fullmatch(w) or w.isdigit() for w in words):
        return False
    # A trailing unit with a leading number is still a quantity ("8 degrees").
    if len(words) >= 2 and words[-1] in _UNIT_WORDS and any(
        _DIGIT_RE.search(w) for w in words[:-1]
    ):
        return False
    return True


# ---------------------------------------------------------------------------
# Regex back-end (fallback — behaviour preserved from the original module)
# ---------------------------------------------------------------------------

def _verb_pattern(verbs: Tuple[str, ...]) -> re.Pattern[str]:
    """Whole-word, case-insensitive alternation over a verb bank."""
    alt = "|".join(re.escape(v) for v in sorted(verbs, key=len, reverse=True))
    return re.compile(rf"\b(?:{alt})s?\b", re.IGNORECASE)


_OUT_VERB_RE = _verb_pattern(_OUTPUT_VERBS)
_IN_VERB_RE = _verb_pattern(_INPUT_VERBS)

# Noun phrase: optional article/determiner + modifiers + head noun.
#
# The modifier run is written as ``(?:word[ ])*?`` with a *possessive* inner
# character class that cannot also match the head noun's leading character in
# more than one way, which keeps this linear rather than exponential on
# backtracking.  (The original nested-quantifier form was ReDoS-prone on long
# unpunctuated spans.)
_NP_RE = re.compile(
    r"""
    (?:(?:a|an|the|this|that|each|every|its|their|all)\s+)?  # optional det.
    (?:[A-Za-z][A-Za-z0-9\-]{1,31}[ ]){0,5}                  # modifiers (bounded)
    [A-Za-z][A-Za-z0-9\-]{2,31}                              # head noun
    """,
    re.VERBOSE | re.IGNORECASE,
)

_BOUNDARY_RE = re.compile(
    r"\b(?:every|each|per|at|in|on|for|from|with|within|by|to|when|whenever"
    r"|if|during|prior|after|once|until|as|and|or|via)\b",
    re.IGNORECASE,
)


def _extract_np_after_verb(sentence: str, verb_re: re.Pattern[str]) -> List[str]:
    """Find each verb occurrence in *sentence* and extract the NP that follows."""
    results: List[str] = []
    for m in verb_re.finditer(sentence):
        tail = sentence[m.end():].lstrip()
        art_m = _ARTICLE_RE.match(tail)
        offset = art_m.end() if art_m else 0
        bound_m = _BOUNDARY_RE.search(tail, offset)
        segment = tail[:bound_m.start()] if bound_m else tail
        np_m = _NP_RE.match(segment.strip())
        if np_m:
            norm = _normalize(np_m.group(0).strip())
            if _acceptable_artifact(norm):
                results.append(norm)
    return results


# Sentence splitter (simple — splits on ". ", "; ", or newline).
_SENT_SPLIT_RE = re.compile(r"(?<=[.;])\s+|\n")


def _sentences(text: str) -> List[str]:
    return [s.strip() for s in _SENT_SPLIT_RE.split(text) if s.strip()]


# ---------------------------------------------------------------------------
# spaCy back-end
# ---------------------------------------------------------------------------

# Object-like dependency roles that carry the artifact in *active* voice.
_ACTIVE_OBJECT_DEPS = frozenset({"dobj", "attr", "oprd"})

# The parser sometimes reads "fetch the event timeline" as a clausal complement
# rather than a direct object.  A *noun-headed* ccomp under a verb from either
# bank is a misparsed object in practice, so it is accepted alongside `dobj`.
_CLAUSAL_OBJECT_DEPS = frozenset({"ccomp"})

# Upper bound on a rebuilt artifact phrase, in tokens, when spaCy gives us no
# noun chunk to anchor on.
_MAX_SPAN_TOKENS = 5

# In *passive* voice the grammatical subject is the artifact
# ("the altitude report shall be generated by the nav unit").
_PASSIVE_SUBJECT_DEPS = frozenset({"nsubjpass", "nsubj:pass"})

# Verb+preposition frames whose prepositional object is a consumed artifact.
# Deliberately an explicit allow-list: a bare "prep -> pobj" walk would harvest
# recipients ("transmit telemetry **to the ground station**") and measurement
# qualifiers ("at 20 Hz") as if they were artifacts.
_PREP_CONSUMER_FRAMES = frozenset({
    ("depend", "on"), ("depend", "upon"),
    ("rely", "on"), ("rely", "upon"),
    ("base", "on"), ("base", "upon"),
    ("act", "on"), ("operate", "on"), ("trigger", "on"),
    ("respond", "to"), ("react", "to"),
    ("listen", "to"), ("subscribe", "to"),
    ("derive", "from"),
})

_SPACY_MODEL = os.getenv("REQCLUSTER_SPACY_MODEL", "en_core_web_sm")

# Cached pipeline. ``False`` is the sentinel for "tried and unavailable" so the
# import cost / warning is paid at most once per process.
_nlp: Any = None
_nlp_loaded = False


def _load_nlp() -> Any:
    """Load and cache the spaCy pipeline, or return ``None`` if unavailable.

    Note the pipeline keeps ``tagger``/``attribute_ruler``/``lemmatizer``: verb
    matching is done on *lemmas* ("generates" -> "generate"), so disabling the
    lemmatizer would silently reduce extraction to exact surface forms.  Only
    the NER component — genuinely unused here — is disabled.
    """
    global _nlp, _nlp_loaded
    if _nlp_loaded:
        return _nlp

    _nlp_loaded = True
    if os.getenv("REQCLUSTER_DISABLE_SPACY", "").strip().lower() in ("1", "true", "yes"):
        logger.info("spaCy disabled via REQCLUSTER_DISABLE_SPACY — using regex extraction.")
        _nlp = None
        return _nlp

    try:
        import spacy  # noqa: PLC0415 — deliberately lazy: keeps import cheap.

        _nlp = spacy.load(_SPACY_MODEL, disable=["ner"])
        logger.info("spaCy artifact extraction enabled (model=%s).", _SPACY_MODEL)
    except (OSError, ImportError) as exc:
        logger.warning(
            "spaCy/%s unavailable (%s) — falling back to regex artifact extraction.",
            _SPACY_MODEL, exc,
        )
        _nlp = None
    return _nlp


def spacy_available() -> bool:
    """True when the spaCy back-end can be used."""
    return _load_nlp() is not None


def reset_nlp_cache() -> None:
    """Clear the cached pipeline. Intended for tests toggling the back-end."""
    global _nlp, _nlp_loaded
    _nlp = None
    _nlp_loaded = False


def _noun_chunk_map(doc: Any) -> Dict[int, Any]:
    """Map each token index to the noun chunk containing it (if any)."""
    mapping: Dict[int, Any] = {}
    try:
        chunks = list(doc.noun_chunks)
    except (NotImplementedError, ValueError):
        # noun_chunks requires a parser; if it is missing, fall back to spans.
        return mapping
    for chunk in chunks:
        for i in range(chunk.start, chunk.end):
            mapping[i] = chunk
    return mapping


def _trailing_gerund(token: Any) -> Any:
    """A deverbal noun immediately after *token* that the tagger read as a verb.

    "the rotor rpm **reading**", "the flight path **planning**" — the head noun
    of the artifact is the ``-ing`` word, but it gets tagged VERB and detached
    from the phrase, truncating the extracted name.  Only a token with no object
    of its own qualifies, so a genuine verb ("… data **feeding** the display")
    is left alone.
    """
    doc = token.doc
    j = token.i + 1
    if j >= len(doc):
        return None
    nxt = doc[j]
    if (
        nxt.pos_ == "VERB"
        and nxt.lower_.endswith("ing")
        and not any(c.dep_ in _ACTIVE_OBJECT_DEPS for c in nxt.children)
    ):
        return nxt
    return None


def _span_text(token: Any, chunks: Dict[int, Any]) -> str:
    """Best-effort surface span naming the artifact headed by *token*.

    Prefers spaCy's own noun chunk; otherwise rebuilds the phrase from the
    token's left-hand ``compound``/``amod``/``nmod`` modifiers.
    """
    chunk = chunks.get(token.i)
    if chunk is not None:
        start, end = chunk.start, chunk.end
    else:
        # Outside any noun chunk — i.e. exactly the misparse cases. The token's
        # left edge recovers the full phrase ("the event timeline"); the width
        # cap stops a badly-attached clause from being swallowed whole.
        start, end = token.i, token.i + 1
        start = max(token.left_edge.i, token.i - _MAX_SPAN_TOKENS)
        for child in token.lefts:
            if child.dep_ in ("compound", "amod", "nmod", "nummod") and child.i < start:
                start = min(start, child.left_edge.i)

    # Pull a mis-tagged deverbal head noun back into the phrase.
    gerund = _trailing_gerund(token.doc[end - 1])
    if gerund is not None:
        end = gerund.i + 1
    text = token.doc[start:end].text

    # "state of charge", "loss of signal": a generic head noun is rescued by its
    # `of`-complement, which is where the actual identity lives.
    if _normalize(text) in _GENERIC:
        for child in token.rights:
            if child.dep_ == "prep" and child.lower_ == "of":
                pobjs = [g for g in child.children if g.dep_ == "pobj"]
                if pobjs:
                    text = token.doc[token.i: pobjs[0].i + 1].text
                    break
    return text


def _conjuncts(token: Any) -> List[Any]:
    """Return *token* plus every token coordinated with it.

    Coordination attaches inconsistently in practice: in "voltage, current, and
    temperature" the later conjuncts may hang off the *verb* rather than the
    first object, and a noun/verb-ambiguous modifier ("heading data") can be
    mis-tagged VERB with its own ``dobj``.  Both shapes are handled by the
    caller; this walks the ordinary noun-to-noun ``conj`` chain.
    """
    out = [token]
    seen = {token.i}
    stack = [token]
    while stack:
        current = stack.pop()
        for child in current.children:
            if child.dep_ == "conj" and child.i not in seen:
                seen.add(child.i)
                out.append(child)
                stack.append(child)
    return out


def _artifacts_from_object(token: Any, chunks: Dict[int, Any]) -> List[str]:
    """Normalized artifact names for an object token and its conjuncts."""
    names: List[str] = []
    for tok in _conjuncts(token):
        if tok.pos_ in ("NUM", "PUNCT", "SYM"):
            continue
        norm = _normalize(_span_text(tok, chunks))
        if _acceptable_artifact(norm):
            names.append(norm)
    return names


def _verb_conjunct_objects(verb: Any, chunks: Dict[int, Any]) -> List[str]:
    """Artifacts hanging off conjuncts of *verb* itself.

    Covers two real parser behaviours:

    * "transmit the battery voltage, the bus current, and the cell temperature"
      — later conjuncts attach to the verb, not to the first object.
    * "output altitude data and heading data" — "heading" is mis-tagged VERB and
      carries its own ``dobj``; the artifact is the span "heading data".
    """
    names: List[str] = []
    for child in verb.children:
        if child.dep_ != "conj":
            continue
        if child.pos_ in ("NOUN", "PROPN"):
            names.extend(_artifacts_from_object(child, chunks))
        elif child.pos_ in ("VERB", "AUX"):
            objs = [g for g in child.children if g.dep_ in _ACTIVE_OBJECT_DEPS]
            for obj in objs:
                # Mis-tagged compound noun: the conjunct word is really the
                # modifier of its own "object" ("heading" + "data").
                if obj.i == child.i + 1 and child.lemma_ not in (
                    _OUTPUT_VERB_SET | _INPUT_VERB_SET
                ):
                    norm = _normalize(child.doc[child.i: obj.i + 1].text)
                    if _acceptable_artifact(norm):
                        names.append(norm)
                else:
                    names.extend(_artifacts_from_object(obj, chunks))
    return names


def _is_passive(verb: Any) -> bool:
    return any(c.dep_ in ("auxpass", "aux:pass") for c in verb.children)


def _extract_artifacts_spacy(doc: Any) -> Tuple[Set[str], Set[str]]:
    """Extract (produced, consumed) artifact names from a parsed document."""
    produced: Set[str] = set()
    consumed: Set[str] = set()
    chunks = _noun_chunk_map(doc)

    for token in doc:
        if token.pos_ not in ("VERB", "AUX"):
            continue
        lemma = token.lemma_.lower()
        is_output = lemma in _OUTPUT_VERB_SET
        is_input = lemma in _INPUT_VERB_SET
        if not (is_output or is_input):
            continue

        sink = produced if is_output else consumed
        passive = _is_passive(token)

        for child in token.children:
            # Passive subject is the artifact; the `by`-agent is the *actor* and
            # must never be harvested ("generated **by the nav unit**").
            if child.dep_ in _PASSIVE_SUBJECT_DEPS:
                sink.update(_artifacts_from_object(child, chunks))
            elif child.dep_ in _ACTIVE_OBJECT_DEPS and not passive:
                sink.update(_artifacts_from_object(child, chunks))
            elif (
                child.dep_ in _CLAUSAL_OBJECT_DEPS
                and not passive
                and child.pos_ in ("NOUN", "PROPN")
            ):
                sink.update(_artifacts_from_object(child, chunks))
            elif child.dep_ == "prep":
                if (lemma, child.lower_) in _PREP_CONSUMER_FRAMES:
                    for grandchild in child.children:
                        if grandchild.dep_ == "pobj":
                            consumed.update(
                                _artifacts_from_object(grandchild, chunks)
                            )

        if not passive:
            sink.update(_verb_conjunct_objects(token, chunks))

    return produced, consumed


