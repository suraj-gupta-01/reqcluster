_SIM_BLOCK_DISPLAY = 512


def section_robustness() -> None:
    from core.dependency_tree import (
        MAX_PAIRS_PER_ARTIFACT,
        _SIM_BLOCK,
        build_dependency_tree,
    )

    global _SIM_BLOCK_DISPLAY
    _SIM_BLOCK_DISPLAY = _SIM_BLOCK

    banner(5, "ROBUSTNESS — the fixes that do not show up in a metric")

    from sklearn.metrics.pairwise import cosine_similarity

    print(f"  {BOLD}Pass 2 no longer materialises the N x N similarity matrix{RESET}")
    print(f"  {DIM}Measuring the array that actually differs, rather than process")
    print("  memory: numpy allocations are invisible to tracemalloc, so a peak-RSS")
    print(f"  figure here would be noise.{RESET}\n")

    for n in (4000, 8000):
        rng = np.random.default_rng(0)
        embeddings = rng.standard_normal((n, 64)).astype(np.float32)
        matrix = cosine_similarity(embeddings)
        block_bytes = _SIM_BLOCK_DISPLAY * n * matrix.dtype.itemsize
        print(f"    N={n:<6} before: one {n}x{n} {matrix.dtype} array = "
              f"{matrix.nbytes / 1e6:>7.0f} MB")
        print(f"    {'':<8} after : one {_SIM_BLOCK_DISPLAY}x{n} block      = "
              f"{block_bytes / 1e6:>7.0f} MB   "
              f"{GREEN}{matrix.nbytes / block_bytes:.0f}x smaller{RESET}")
        del matrix

    print(f"\n    {DIM}The saving is quadratic in N, so it is invisible on a small")
    print("    dataset and decisive on a large one: at N=35000 the old array")
    print("    alone is 9.8 GB. Runtime at these sizes is unchanged - this fix")
    print(f"    is about not falling over, not about speed.{RESET}\n")

    print(f"  {BOLD}Ragged input: fewer ids than texts used to raise IndexError{RESET}")
    tree = build_dependency_tree(
        np.zeros((3, 8), dtype=np.float32),
        ["a shall generate x", "b shall use x", "c"], ["R1"], np.array([0]),
    )
    print(f"    ids recovered: {[n['node_id'] for n in tree['nodes']]}\n")

    print(f"  {BOLD}Fan-out cap: one over-shared artifact name cannot flood the graph{RESET}")
    many = ["The unit shall generate the shared telemetry frame."] * 30 + \
           ["The unit shall receive the shared telemetry frame."] * 30
    tree = build_dependency_tree(
        np.zeros((60, 8), dtype=np.float32), many,
        [f"REQ-{i:03d}" for i in range(60)], np.full(60, -1),
        enable_artifact_near_match=False,
    )
    print(f"    30 producers x 30 consumers = 900 pairs, over the "
          f"{MAX_PAIRS_PER_ARTIFACT} cap")
    print(f"    edges emitted: {tree['stats']['n_edges']} "
          f"(artifacts skipped: {tree['stats'].get('artifacts_skipped_fanout_cap', 0)})\n")

    print(f"  {BOLD}Graceful degradation: no spaCy, no failure{RESET}")
    print(f"    {DIM}REQCLUSTER_DISABLE_SPACY=1 forces the regex path; the engine keeps")
    print(f"    running with lower recall rather than erroring.{RESET}")


SECTIONS = {
    1: ("problem + fix", lambda quick: section_problem_and_fix()),
    2: ("problem + fix", lambda quick: None),
    3: ("measure", section_measure),
    4: ("explainability", lambda quick: section_explain()),
    5: ("robustness", lambda quick: section_robustness()),
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--section", type=int, choices=[1, 3, 4, 5], default=None,
                        help="Run only one section (1 covers both 1 and 2).")
    parser.add_argument("--quick", action="store_true",
                        help="Skip the slower scoring comparison.")
    args = parser.parse_args()

    print(f"\n{BOLD}ReqCluster — dependency engine hardening{RESET}")
    print(f"{DIM}Everything below is computed live, offline.{RESET}")

    if args.section in (None, 1):
        section_problem_and_fix()
    if args.section in (None, 3) and not (args.quick and args.section is None):
        section_measure(args.quick)
    if args.section in (None, 4):
        section_explain()
    if args.section in (None, 5):
        section_robustness()

    print(f"\n{BOLD}{GREEN}Done.{RESET} Full reports live in eval-results/.\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
