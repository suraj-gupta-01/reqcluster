#!/usr/bin/env python
"""Live demo of the DP5 dependency-engine hardening.

Walks through the story end to end, computing every number on the spot rather
than reading canned output:

    1. The problem   - what the regex extractor misses, on real sentences
    2. The fix       - the same sentences through the spaCy dependency parse
    3. The measure   - harness scores, old engine vs new, on both gold sets
    4. Explainability - one edge's structured evidence and its explanation
    5. Robustness    - the scale and correctness fixes, demonstrated

Usage::

    python tools/demo_dependency_hardening.py            # full walkthrough
    python tools/demo_dependency_hardening.py --section 3
    python tools/demo_dependency_hardening.py --quick    # skip the slow scoring

Everything runs offline. No LLM or network call is made.
"""

