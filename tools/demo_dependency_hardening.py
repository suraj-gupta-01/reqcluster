# (case, sentence, artifacts a correct extractor should find)
DEMO_SENTENCES = [
    ("Passive voice",
     "The altitude report shall be generated by the navigation unit.",
     {"altitude report"}),
    ("Passive voice",
     "The cabin pressure value shall be generated by the environmental sensor at 10 Hz.",
     {"cabin pressure value"}),
    ("Coordination",
     "The sensor fusion module shall output altitude data and heading data at 20 Hz.",
     {"altitude data", "heading data"}),
    ("Coordination",
     "The telemetry encoder shall transmit the battery voltage, the bus current, "
     "and the cell temperature once per second.",
     {"battery voltage", "bus current", "cell temperature"}),
    ("Passive + coordination",
     "The attitude quaternion and the angular rate vector shall be produced by "
     "the inertial reference system.",
     {"attitude quaternion", "angular rate vector"}),
    ("Verb + preposition",
     "The guidance module shall depend on the position fix.",
     {"position fix"}),
]


def _verdict(found: set, expected: set) -> str:
    """PASS only when every expected artifact was extracted."""
    if expected <= found:
        return f"{GREEN}PASS{RESET}"
    if found & expected:
        return f"{YELLOW}PART{RESET}"
    return f"{RED}FAIL{RESET}"


def section_problem_and_fix() -> None:
    from core.artifact_extractor import extract_artifacts, spacy_available

    banner(1, "THE PROBLEM — what the regex extractor misses")
    print(f"{DIM}Pass 0 links a requirement that PRODUCES an artifact to one that")
    print(f"CONSUMES it. That only works if the artifact is extracted correctly.{RESET}\n")

    texts = [t for _, t, _ in DEMO_SENTENCES]
    ids = [f"D-{i:03d}" for i in range(len(texts))]
    regex = extract_artifacts(texts, ids, use_spacy=False)

    regex_pass = 0
    for (kind, text, expected), art in zip(DEMO_SENTENCES, regex):
        found = art.produced | art.consumed
        regex_pass += expected <= found
        print(f"  [{kind}]  {_verdict(found, expected)}")
        print(f"    {DIM}{text}{RESET}")
        print(f"    should find : {sorted(expected)}")
        print(f"    regex found : {sorted(found) or '(nothing)'}\n")
    print(f"  {BOLD}regex: {regex_pass}/{len(DEMO_SENTENCES)} sentences "
          f"fully extracted{RESET}")

    banner(2, "THE FIX — the same sentences through a dependency parse")
    if not spacy_available():
        print(f"{YELLOW}spaCy/en_core_web_sm not installed — the engine falls back to")
        print("the regex path automatically and nothing breaks, but this section")
        print(f"needs the model:  python -m spacy download en_core_web_sm{RESET}")
        return

    spacy_out = extract_artifacts(texts, ids, use_spacy=True)
    spacy_pass = 0
    for (kind, text, expected), before, after in zip(DEMO_SENTENCES, regex, spacy_out):
        before_found = before.produced | before.consumed
        found = after.produced | after.consumed
        spacy_pass += expected <= found
        print(f"  [{kind}]  {_verdict(found, expected)}")
        print(f"    {DIM}{text}{RESET}")
        print(f"    {RED}regex :{RESET} {sorted(before_found) or '(nothing)'}")
        print(f"    {GREEN}spaCy :{RESET} produces={sorted(after.produced) or '-'}  "
              f"consumes={sorted(after.consumed) or '-'}\n")
    print(f"  {BOLD}regex: {regex_pass}/{len(DEMO_SENTENCES)}    "
          f"spaCy: {spacy_pass}/{len(DEMO_SENTENCES)} sentences fully extracted{RESET}\n")

    print(f"{DIM}Note the passive cases: the artifact is the grammatical *subject*")
    print("('the altitude report shall be generated by ...'), which a scanner")
    print("looking only after the verb can never reach. The 'by ...' agent is the")
    print(f"actor and is deliberately NOT captured as an artifact.{RESET}")


