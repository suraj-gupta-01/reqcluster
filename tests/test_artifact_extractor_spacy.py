def test_regex_fallback_returns_the_same_shape():
    result = _extract_one(
        "The system shall generate an altitude report every second.",
        use_spacy=False,
    )
    assert result.req_id == "REQ-001"
    assert result.req_index == 0
    assert isinstance(result.produced, set)
    assert isinstance(result.consumed, set)
    assert "altitude report" in result.produced


def test_unavailable_spacy_falls_back_silently(monkeypatch):
    """Simulate a missing model: extraction must degrade, never raise."""
    monkeypatch.setattr(extractor, "_nlp", None)
    monkeypatch.setattr(extractor, "_nlp_loaded", True)

    result = _extract_one("The system shall generate an altitude report.")
    assert "altitude report" in result.produced


def test_import_failure_is_handled(monkeypatch):
    """An ImportError from spacy.load must not propagate to the caller."""
    import builtins

    real_import = builtins.__import__

    def fake_import(name, *args, **kwargs):
        if name == "spacy":
            raise ImportError("simulated missing spacy")
        return real_import(name, *args, **kwargs)

    extractor.reset_nlp_cache()
    monkeypatch.setattr(builtins, "__import__", fake_import)

    assert extractor._load_nlp() is None
    assert extractor.spacy_available() is False


def test_disable_env_var_forces_the_regex_path(monkeypatch):
    monkeypatch.setenv("REQCLUSTER_DISABLE_SPACY", "1")
    extractor.reset_nlp_cache()
    assert extractor._load_nlp() is None


def test_requesting_spacy_when_unavailable_raises(monkeypatch):
    """Explicit ``use_spacy=True`` is a contract, so it fails loudly."""
    monkeypatch.setattr(extractor, "_nlp", None)
    monkeypatch.setattr(extractor, "_nlp_loaded", True)

    with pytest.raises(RuntimeError, match="unavailable"):
        extract_artifacts(["The system shall generate a report."], ["REQ-001"],
                          use_spacy=True)


def test_mismatched_req_ids_do_not_truncate_results():
    """Fewer ids than texts used to silently drop the trailing requirements."""
    texts = [
        "The system shall generate an altitude report.",
        "The display shall receive the altitude report.",
        "The logger shall store the fault record.",
    ]
    result = extract_artifacts(texts, ["REQ-001"])
    assert len(result) == 3
    assert result[1].req_id == "REQ-002"
    assert result[2].req_id == "REQ-003"


def test_non_string_texts_are_tolerated():
    result = extract_artifacts([None, 42, "The unit shall generate a fault code."],
                               ["A", "B", "C"])
    assert len(result) == 3
    assert not result[0].produced
    assert not result[1].produced


