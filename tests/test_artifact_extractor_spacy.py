@pytest.fixture(autouse=True)
def _reset_backend():
    """Keep the module-level pipeline cache from leaking between tests."""
    extractor.reset_nlp_cache()
    yield
    extractor.reset_nlp_cache()


def _extract_one(text, use_spacy=None):
    return extract_artifacts([text], ["REQ-001"], use_spacy=use_spacy)[0]


