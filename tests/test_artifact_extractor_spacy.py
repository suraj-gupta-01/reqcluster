def test_verb_banks_come_from_the_shared_lexicon():
    """One source of truth: the module re-exports rather than redefining."""
    assert extractor._OUTPUT_VERBS is OUTPUT_VERBS
    assert extractor._INPUT_VERBS is INPUT_VERBS


def test_verb_banks_do_not_overlap():
    """A verb in both banks would make a requirement its own producer/consumer."""
    assert not (set(OUTPUT_VERBS) & set(INPUT_VERBS))


