def _fake_embedder(vectors_by_name):
    import numpy as np

    def embed(names):
        return np.asarray([vectors_by_name[n] for n in names], dtype=np.float32)

    return embed


def test_near_match_merges_synonyms_under_one_canonical_name():
    producers = {"temperature reading": [0]}
    consumers = {"temp value": [1]}
    embed = _fake_embedder({
        "temperature reading": [1.0, 0.0],
        "temp value": [0.99, 0.14],
    })

    new_p, new_c, report = resolve_near_matches(
        producers, consumers, similarity_threshold=0.80, embed_fn=embed
    )

    assert len(report["merges"]) == 1
    canonical = report["merges"][0]["to"]
    assert set(new_p) == {canonical}
    assert set(new_c) == {canonical}
    assert new_p[canonical] == [0]
    assert new_c[canonical] == [1]


def test_near_match_leaves_distinct_names_alone():
    producers = {"altitude report": [0]}
    consumers = {"battery voltage": [1]}
    embed = _fake_embedder({
        "altitude report": [1.0, 0.0],
        "battery voltage": [0.0, 1.0],
    })

    new_p, new_c, report = resolve_near_matches(
        producers, consumers, similarity_threshold=0.80, embed_fn=embed
    )

    assert report["merges"] == []
    assert new_p == producers
    assert new_c == consumers


def test_near_match_canonical_choice_is_deterministic():
    """Shorter name wins; ties break lexicographically."""
    embed = _fake_embedder({"temp value": [1.0, 0.0], "temperature reading": [1.0, 0.0]})

    first = resolve_near_matches(
        {"temperature reading": [0]}, {"temp value": [1]},
        similarity_threshold=0.5, embed_fn=embed,
    )[2]
    second = resolve_near_matches(
        {"temperature reading": [0]}, {"temp value": [1]},
        similarity_threshold=0.5, embed_fn=embed,
    )[2]

    assert first["merges"] == second["merges"]
    assert first["merges"][0]["to"] == "temp value"


def test_near_match_skips_when_embedding_fails():
    def boom(_names):
        raise RuntimeError("no model")

    producers, consumers = {"a name": [0]}, {"another name": [1]}
    new_p, new_c, report = resolve_near_matches(
        producers, consumers, embed_fn=boom
    )

    assert report["skipped"]
    assert new_p == producers
    assert new_c == consumers


def test_near_match_is_a_no_op_without_both_sides():
    new_p, new_c, report = resolve_near_matches({"x name": [0]}, {})
    assert report["skipped"]
    assert new_p == {"x name": [0]}
    assert new_c == {}


def test_near_match_respects_the_name_count_guard(monkeypatch):
    monkeypatch.setattr(extractor, "MAX_NEAR_MATCH_NAMES", 1)
    producers = {"first name": [0], "second name": [1]}
    consumers = {"third name": [2]}

    _, _, report = resolve_near_matches(producers, consumers)

    assert "exceeds" in (report["skipped"] or "")



