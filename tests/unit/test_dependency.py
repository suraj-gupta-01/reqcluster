def test_import_failure_is_handled(monkeypatch):
    """An ImportError from spacy.load must not propagate to the caller."""
    import builtins

    real_import = builtins.__import__

    def fake_import(name, *args, **kwargs):
        if name == "spacy":
            raise ImportError("simulated missing spacy")
        return real_import(name, *args, **kwargs)

    extractor.reset_nlp_cache()
    monkeypatch.setattr(builtins, "__import__", fake_import)

    assert extractor._load_nlp() is None
    assert extractor.spacy_available() is False


